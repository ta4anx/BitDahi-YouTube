from manim import*
class UsluGiris(Scene):
    def construct(self):
        carpma = Text("Çarpma işleminin nasıl yapıldığını biliyoruz.")
        self.play(Write(carpma))
        self.wait(2)
        four_times_six = MathTex("4 \\times 6")
        four_times_six.scale(1.5)
        equ = MathTex("= 24")
        equ.scale(1.5)
        equ.next_to(four_times_six, RIGHT)
        self.play(Transform(carpma, four_times_six))
        self.wait(1)
        self.play(Write(equ))
        self.wait(1)
        self.play(FadeOut(equ))
        self.wait(1)
        self.play(carpma.animate.move_to(ORIGIN + LEFT * 2))
        four_times_six.move_to(ORIGIN + LEFT * 2)
        equa = MathTex("=")
        equa.scale(1.5)
        equa.next_to(four_times_six, RIGHT)
        six_plus = MathTex(" 6 + 6 + 6 + 6")
        six_plus.scale(1.5)
        six_plus.next_to(equa, RIGHT)
        self.play(Write(equa), Write(six_plus))
        self.wait(1)
        brace = Brace(six_plus, DOWN)
        explanation = Text("4 kez 6'nın kendisi\n ile toplanmasıdır.")
        explanation.scale(0.8)
        explanation.next_to(brace, DOWN)
        self.play(Write(brace), Write(explanation))
        self.wait(2)
        four_plus = MathTex("4 + 4 + 4 + 4 + 4 + 4")
        four_plus.scale(1.5)
        four_plus.next_to(equa, RIGHT)
        explanation2 = Text("6 kez 4'ün kendisi\n ile toplanmasıdır.")
        explanation2.scale(0.8)
        # Move the brace to match the new four_plus object
        brace_new = Brace(four_plus, DOWN)
        explanation2.next_to(brace_new, DOWN)
        self.play(Transform(brace, brace_new),Transform(six_plus, four_plus), TransformMatchingShapes(explanation, explanation2))
        self.wait(2)
        self.play(FadeOut(VGroup(carpma, four_times_six, equa, six_plus, brace, explanation2)))
        self.wait(1)
        AtimesN = MathTex("a \\times n")
        AtimesN.scale(1.5)
        AtimesN.move_to(ORIGIN)
        self.play(Write(AtimesN))
        self.wait(2)
        AtimesN_expanded = MathTex("a \\times n = a + a + \\ldots + a \\quad")
        AtimesN_expanded.scale(1.5)
        AtimesN_expanded.move_to(ORIGIN)
        # Find the part "a + a + \ldots + a" in AtimesN_expanded and add a brace only to that part
        aplus = AtimesN_expanded[0][4:20]  # This slices the "a + a + \ldots + a" part
        aplusBracket = Brace(aplus, DOWN)
        nkeretext = Text("n tane a'nın toplanmasıdır.")
        nkeretext.scale(0.8)
        nkeretext.next_to(aplusBracket, DOWN)
        self.play(TransformMatchingShapes(AtimesN, AtimesN_expanded),
                  Write(aplusBracket), Write(nkeretext))
        self.wait(2)
        self.play(FadeOut(VGroup(AtimesN_expanded, aplusBracket, nkeretext)))